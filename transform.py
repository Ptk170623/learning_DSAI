def _rank(table: pd.DataFrame, suffix: str, magnitude, cutoff_pct: float | None) -> pd.DataFrame:
    filtered = table[table["classification"].str.endswith(suffix)].copy()
    if filtered.empty:
        return filtered.assign(percentage=pd.Series(dtype=float))
    filtered["magnitude"] = magnitude(filtered["current_value"], filtered["benchmark"])
    total = filtered["magnitude"].sum()
    filtered["percentage"] = filtered["magnitude"] / total * 100
    if cutoff_pct is not None:
        filtered = filtered[filtered["percentage"] >= cutoff_pct]
    return filtered.sort_values("percentage", ascending=False).reset_index(drop=True)


def drops(base_table: pd.DataFrame, cutoff_pct: float | None) -> pd.DataFrame:
    return _rank(base_table, "BELOW", lambda current, benchmark: benchmark - current, cutoff_pct)


def rises(base_table: pd.DataFrame, cutoff_pct: float | None) -> pd.DataFrame:
    return _rank(base_table, "ABOVE", lambda current, benchmark: current - benchmark, cutoff_pct)


