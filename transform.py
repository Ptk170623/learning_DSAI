def _is_isolate(product: str) -> bool:
    return str(product).upper().startswith("CANABIDIOL") or str(product).upper().startswith("ISOLATE")


@dataclass
class DataDoctorPotential:
    px_doctor: pd.DataFrame     # block, crm_uf, product_type, laboratory, doctor_name, px (most recent MAT)
    px_product: pd.DataFrame    # crm_uf, product, laboratory, product_type, px
