def _effort_bucket(crm_uf: str, panel_by_crm: dict[str, float]) -> str:
    """"Outside Panel": crm_uf absent from painel.parquet entirely. "Never
    Visited": in the panel, DIAS_SEM_VISITA_NUM blank. "Visited": in the
    panel, more than DAYS_RECENT_VISIT days since the last visit. "Visited
    Recently": DAYS_RECENT_VISIT days or fewer. Mutually exclusive - every
    doctor falls into exactly one."""
    if crm_uf not in panel_by_crm:
        return "Outside Panel"
    days = panel_by_crm[crm_uf]
    if pd.isna(days):
        return "Never Visited"
    return "Visited Recently" if days <= DAYS_RECENT_VISIT else "Visited"


def calculate_table_doctor_potential(data: DataDoctorPotential, block: str | None, laboratory: str | None, product_type: str, effort: str, result: str) -> pd.DataFrame:
    columns = ["doctor_name", "crm_uf", "blocks", "px", "effort", "result", "reason"]
    px = data.px_doctor
    if block is not None:
        px = px[px["block"] == block]
    if laboratory is not None:
        px = px[px["laboratory"] == laboratory]
    if product_type != "All":
        px = px[px["product_type"] == product_type]
    if px.empty:
        return pd.DataFrame(columns=columns)

    by_doctor = px.groupby("crm_uf").agg(
        doctor_name=("doctor_name", "first"), px=("px", "sum"),
        blocks=("block", lambda s: ", ".join(sorted(s.unique()))),
    ).reset_index()

    panel_by_crm = dict(zip(data.panel["crm_uf"], data.panel["days_since_visit"]))
    by_doctor["effort"] = [_effort_bucket(crm, panel_by_crm) for crm in by_doctor["crm_uf"]]

    if data.mat_anchor is None:
        by_doctor["result"] = 0.0
    else:
        window_start = data.mat_anchor - pd.DateOffset(months=11)
        window_end = data.mat_anchor + pd.DateOffset(months=1)
        rev = data.revenue_1015
        rev_window = rev[(rev["month"] >= window_start) & (rev["month"] < window_end)]
        rev_by_doctor = rev_window.groupby("crm_uf", as_index=False)["revenue"].sum()
        by_doctor = by_doctor.merge(rev_by_doctor, on="crm_uf", how="left")
        by_doctor["result"] = by_doctor["revenue"].fillna(0.0)

    if effort != "All":
        by_doctor = by_doctor[by_doctor["effort"] == effort]
    if result == "No Result":
        by_doctor = by_doctor[by_doctor["result"] == 0]
    elif result == "With Result":
        by_doctor = by_doctor[by_doctor["result"] > 0]

    by_doctor["reason"] = ""  # no local source yet for this - see module docstring.
    return by_doctor[columns].sort_values("px", ascending=False).reset_index(drop=True)


def calculate_products_doctor_potential(data: DataDoctorPotential, crm_uf: str) -> pd.DataFrame:
    columns = ["product", "laboratory", "product_type", "px"]
    crm_normalized = (crm_uf or "").strip().upper()
    if not crm_normalized:
        return pd.DataFrame(columns=columns)
    found = data.px_product[data.px_product["crm_uf"].str.upper() == crm_normalized]
    return found[columns].sort_values("px", ascending=False).reset_index(drop=True)
