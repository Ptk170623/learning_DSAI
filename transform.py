def _most_recent_mat(per_nome: pd.Series) -> tuple[str | None, pd.Timestamp | None]:
    """Finds the most recent PER_NOME ("MAT MM/AA") among the distinct
    values in the column - returns (original_value, anchor_month) or
    (None, None) if there is no recognizable PER_NOME at all."""
    import re
    pattern = re.compile(r"(\d{2})/(\d{2})")
    dates = {}
    for periodo in per_nome.dropna().unique():
        match = pattern.search(str(periodo))
        if match:
            month, year = int(match.group(1)), int(match.group(2))
            dates[periodo] = pd.Timestamp(year=2000 + year, month=month, day=1)
    if not dates:
        return None, None
    current_period = max(dates, key=dates.get)
    return current_period, dates[current_period]


def load_data_doctor_potential() -> DataDoctorPotential:
    closeup = _ler("closeup")
    current_period, mat_anchor = _most_recent_mat(closeup["PER_NOME"])
    current = closeup if current_period is None else closeup[closeup["PER_NOME"] == current_period]

    current = current.copy()
    current["block"] = current["NOME_BLOCO"].fillna(NOT_INFORMED)
    current["crm_uf"] = current["CRM - UF"].fillna(NOT_INFORMED)
    current["product_type"] = np.where(current["PRODUTO"].apply(_is_isolate), "Isolate", "Full Spectrum")

    px_doctor = current.groupby(["block", "crm_uf", "product_type", "LABORATORIO"], as_index=False).agg(
        doctor_name=("NOME_MEDICO", "first"), px=("PX", "sum"),
    ).rename(columns={"LABORATORIO": "laboratory"})
    px_product = current.groupby(["crm_uf", "PRODUTO", "LABORATORIO", "product_type"], as_index=False).agg(
        px=("PX", "sum"),
    ).rename(columns={"PRODUTO": "product", "LABORATORIO": "laboratory"})

    v1015 = _ler("vendas_1015").copy()
    v1015["month"] = v1015["DATA"].dt.to_period("M").dt.to_timestamp()
    revenue_1015 = v1015.groupby(["CRM_UF", "BLOCO", "month"], as_index=False)["VALOR_REPRESENTANTE"].sum().rename(
        columns={"CRM_UF": "crm_uf", "BLOCO": "block", "VALOR_REPRESENTANTE": "revenue"},
    )

    panel = _ler("painel")[["CRM - UF", "DIAS_SEM_VISITA_NUM"]].rename(
        columns={"CRM - UF": "crm_uf", "DIAS_SEM_VISITA_NUM": "days_since_visit"},
    )
    return DataDoctorPotential(px_doctor, px_product, revenue_1015, panel, mat_anchor)


