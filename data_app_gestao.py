def format_currency(value) -> str:
    if value is None or pd.isna(value):
        return "-"
    text = f"{value:,.2f}"
    return "R$ " + text.replace(",", "X").replace(".", ",").replace("X", ".")


def format_integer(value) -> str:
    if value is None or pd.isna(value):
        return "-"
    return str(int(round(value)))


