def page_rep_block_performance() -> None:
    st.header("Rep Block Performance")
    st.caption(
        "1st section: Doctor Potential - crosses external market potential (Closeup, PX in the most "
        "recent MAT) with effort (panel presence/visit, classified locally - no external system is "
        "read here) and internal result (1015 revenue)."
    )

    data = _cached_data_doctor_potential()
    blocks = transform.blocks_available_doctor_potential(data)
    if not blocks:
        st.info("Not enough market data (Closeup) for this analysis.")
        return

    mat_text = data.mat_anchor.strftime("%m/%Y") if data.mat_anchor is not None else "-"
    st.caption(
        f"PX in the most recent available MAT ({mat_text}); Result = internal revenue (\"1015 Sales\", "
        "VALOR_REPRESENTANTE) in the same 12-month window ending at the MAT."
    )

    st.subheader("Doctor Potential")
    c1, c2, c3 = st.columns(3)
    block_label = c1.selectbox("Block", ["All"] + blocks, index=0, key="block_doctor_potential")
    block = None if block_label == "All" else block_label
    laboratories = transform.laboratories_available_doctor_potential(data)
    laboratory_label = c2.selectbox("Laboratory", ["All"] + laboratories, index=0, key="laboratory_doctor_potential")
    laboratory = None if laboratory_label == "All" else laboratory_label
    product_type = c3.selectbox("Product Type", ["All", "Isolate", "Full Spectrum"], index=0, key="product_type_doctor_potential")

    c4, c5 = st.columns(2)
    effort = c4.selectbox(
        "Effort", transform.EFFORTS, index=0, key="effort_doctor_potential",
        help=(
            '"Outside Panel": no record for that CRM-UF in the local panel data. "Never Visited": in '
            'the panel, but no visit date on record. "Visited": visited, but more than '
            f'{transform.DAYS_RECENT_VISIT} days ago. "Visited Recently": visited within the last '
            f'{transform.DAYS_RECENT_VISIT} days. Mutually exclusive - every doctor falls into exactly one.'
        ),
    )
    result_label = c5.selectbox(
        "Result", transform.RESULTS, index=0, key="result_doctor_potential",
        help='"No Result" = R$ 0.00 internal revenue in the window; "With Result" = any value above R$ 0.00.',
    )

    table = transform.calculate_table_doctor_potential(data, block, laboratory, product_type, effort, result_label)
    if table.empty:
        st.info("No doctor in the selected scope.")
    else:
        exibir = pd.DataFrame({
            "Doctor": table["doctor_name"],
            "CRM-UF": table["crm_uf"],
            "Blocks": table["blocks"],
            "PX (MAT)": table["px"],
            "Effort": table["effort"],
            "Result": table["result"],
            "Reason": table["reason"],
        })
        st.dataframe(
            exibir, use_container_width=True, hide_index=True,
            column_config={"PX (MAT)": _UNITS_COLUMN, "Result": _CURRENCY_COLUMN},
        )

    st.subheader("By Product")
    st.caption(
        "Search a doctor's CRM-UF (as it appears above) to see PX by laboratory/product in the "
        "market, in the same MAT - Isolate and Full Spectrum together, regardless of the \"Product "
        "Type\" segmenter chosen above."
    )
    crm_uf_potential = st.text_input("Doctor CRM-UF", key="crm_uf_doctor_potential")
    if not crm_uf_potential.strip():
        st.caption("Type a CRM-UF above to see the products.")
    else:
        products = transform.calculate_products_doctor_potential(data, crm_uf_potential)
        if products.empty:
            st.info("No market product found for this CRM-UF in the most recent MAT.")
        else:
            exibir_products = pd.DataFrame({
                "Product": products["product"],
                "Laboratory": products["laboratory"],
                "Product Type": products["product_type"],
                "PX": products["px"],
            })
            st.dataframe(
                exibir_products, use_container_width=True, hide_index=True,
                column_config={"PX": _UNITS_COLUMN},
            )


