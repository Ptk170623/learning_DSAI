def page_660_analysis() -> None:
    st.header("660 Analysis")
    st.caption(
        "Own-brand internal sales compared against a retroactive benchmark window (excludes the "
        "current period), classified by % deviation."
    )

    data = _cached_data_660()
    blocks = transform.blocks_available(data)
    months = transform.months_available(data)
    if not blocks or not months:
        st.info("Not enough own-brand sales data for this analysis.")
        return

    c1, c2, c3, c4, c5 = st.columns(5)
    block_label = c1.selectbox("Block", ["All"] + blocks, index=0, key="block_660")
    block = None if block_label == "All" else block_label
    month = c2.selectbox(
        "Month", months, index=len(months) - 1, format_func=lambda m: m.strftime("%m/%Y"), key="month_660",
    )
    months_in_current_period = _select_months_in_current_period(c3, "months_current_660")
    client_effort = c4.radio("Client Effort", ["Yes", "All"], horizontal=True, key="effort_660")
    payment_type = c5.selectbox("Payment Type", PAYMENT_TYPES, index=2, key="payment_660")

    c6, c7, c8 = st.columns(3)
    window = c6.selectbox("Benchmark Period", list(transform.BENCHMARK_WINDOWS.keys()), key="window_660")
    measure = c7.radio("Summary Measure", ["Mean", "Median"], horizontal=True, key="measure_660")
    selection = _select_month_selection(c8, "selection_660")

    explanation = _current_period_explanation(measure, months_in_current_period)
    if explanation is not None:
        st.info(explanation)

    table = transform.calculate_table_660(
        data, block, client_effort, payment_type, month, window, measure, selection, months_in_current_period,
    )
    exibir = pd.DataFrame({
        "Metric": table["metric"].map(transform.NAME_METRIC),
        _current_period_label(measure, months_in_current_period): table["current_value"],
        f"Benchmark ({measure})": table["benchmark"],
        "Classification": table["classification"],
    })
    st.dataframe(
        exibir, use_container_width=True, hide_index=True,
        column_config={
            _current_period_label(measure, months_in_current_period): _NUMBER_COLUMN,
            f"Benchmark ({measure})": _NUMBER_COLUMN,
        },
    )

    st.subheader("By Sale Type")
    metric_tv = _select_metric("metric_tv_660")
    table_tv = transform.calculate_table_by_sale_type(
        data, block, client_effort, payment_type, month, window, measure, metric_tv, selection, months_in_current_period,
    )
    exibir_tv = pd.DataFrame({
        "Sale Type": table_tv["sale_type"],
        _current_period_label(measure, months_in_current_period): table_tv["current_value"],
        f"Benchmark ({measure})": table_tv["benchmark"],
        "Difference": table_tv["difference"],
        "Classification": table_tv["classification"],
    })
    value_col = _value_config(metric_tv)
    st.dataframe(
        exibir_tv, use_container_width=True, hide_index=True,
        column_config={
            _current_period_label(measure, months_in_current_period): value_col,
            f"Benchmark ({measure})": value_col, "Difference": value_col,
        },
    )

    st.subheader("By Doctor")
    cm1, cm2 = st.columns(2)
    metric_med = cm1.selectbox(
        "Metric", list(transform.NAME_METRIC.keys()), format_func=lambda m: transform.NAME_METRIC[m], key="metric_doctor_660",
    )
    sale_type_label = cm2.selectbox(
        "Sale Type", ["All"] + transform.sale_types_available(data), index=0, key="sale_type_doctor_660",
    )
    sale_type = None if sale_type_label == "All" else sale_type_label
    table_med = transform.calculate_table_by_doctor(
        data, block, client_effort, payment_type, sale_type, month, window, measure, metric_med, selection,
        months_in_current_period,
    )
    if table_med.empty:
        st.info("No doctor with sales in the selected scope.")
    else:
        exibir_med = pd.DataFrame({
            "Doctor": table_med["doctor_name"],
            "CRM-UF": table_med["crm_uf"],
            "Blocks": table_med["blocks"],
            _current_period_label(measure, months_in_current_period): table_med["current_value"],
            f"Benchmark ({measure})": table_med["benchmark"],
            "Difference": table_med["difference"],
            "Classification": table_med["classification"],
        })
        value_col_med = _value_config(metric_med)
        st.dataframe(
            exibir_med, use_container_width=True, hide_index=True,
            column_config={
                _current_period_label(measure, months_in_current_period): value_col_med,
                f"Benchmark ({measure})": value_col_med, "Difference": value_col_med,
            },
        )

    st.subheader("By Product")
    st.caption(
        "Search a doctor's CRM-UF (as it appears in \"By Doctor\" above) to see the drop/rise "
        "product by product - sums every block where that CRM-UF appears, ignoring the \"Block\" "
        "segmenter at the top of the page."
    )
    crm_uf_product = st.text_input("Doctor CRM-UF", key="crm_uf_product_660")
    metric_product = _select_metric("metric_product_660")
    if not crm_uf_product.strip():
        st.caption("Type a CRM-UF above to see the products.")
    else:
        table_product = transform.calculate_table_by_product(
            data, crm_uf_product, client_effort, payment_type, month, window, measure, metric_product,
            selection, months_in_current_period,
        )
        if table_product.empty:
            st.info("No sales for this doctor in the selected scope.")
        else:
            exibir_product = pd.DataFrame({
                "Product": table_product["product"],
                _current_period_label(measure, months_in_current_period): table_product["current_value"],
                f"Benchmark ({measure})": table_product["benchmark"],
                "Difference": table_product["difference"],
                "Classification": table_product["classification"],
            })
            value_col_product = _value_config(metric_product)
            st.dataframe(
                exibir_product, use_container_width=True, hide_index=True,
                column_config={
                    _current_period_label(measure, months_in_current_period): value_col_product,
                    f"Benchmark ({measure})": value_col_product, "Difference": value_col_product,
                },
            )

    st.subheader("Churns in the Month")
    st.caption(
        f"Patients whose projected stock rupture (last own-brand purchase - any product) falls in "
        f"{month:%m/%Y}. Excludes patients flagged as a posologia outlier (POSOLOGIA_SUSPEITA, a "
        "single upper Tukey fence computed upstream per product)."
    )
    churn_data = _cached_data_churns()
    cc1, cc2, cc3 = st.columns(3)
    product_label = cc1.selectbox(
        "Product", ["All"] + transform.products_available_churns(churn_data), key="product_churns",
    )
    product = None if product_label == "All" else product_label
    block_churn_label = cc2.selectbox(
        "Block", ["All"] + transform.blocks_available_churns(churn_data), key="block_churns",
    )
    block_churn = None if block_churn_label == "All" else block_churn_label
    payment_churns = cc3.selectbox("Payment Type", PAYMENT_TYPES, index=2, key="payment_churns")

    result = transform.calculate_churns_in_month(churn_data, month, product, block_churn, payment_churns)
    st.metric("Churns (excluding posologia outliers)", format_integer(result["churn_count"]))
    st.dataframe(result["table"], use_container_width=True, hide_index=True)


