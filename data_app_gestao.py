def _display_ranking(table: pd.DataFrame, metric: str, value_label: str, percent_label: str, include_sale_type: bool = True) -> None:
    if table.empty:
        st.info("No combination reached the selected cutoff in this scope.")
        return
    columns = {"Block": table["block"]}
    if include_sale_type:
        columns["Sale Type"] = table["sale_type"]
    columns["Current Value"] = table["current_value"]
    columns["Benchmark"] = table["benchmark"]
    columns["Classification"] = table["classification"]
    columns[value_label] = table["magnitude"]
    columns[percent_label] = table["percentage"]
    exibir = pd.DataFrame(columns)
    value_col = _value_config(metric)
    st.dataframe(
        exibir, use_container_width=True, hide_index=True,
        column_config={
            "Current Value": value_col, "Benchmark": value_col,
            value_label: value_col, percent_label: _PERCENT_COLUMN,
        },
    )


