def _select_metric(key: str):
    return st.selectbox(
        "Metric", list(transform.NAME_METRIC.keys()), format_func=lambda m: transform.NAME_METRIC[m], key=key,
    )


def _select_month_selection(column, key_prefix: str) -> transform.MonthSelection:
    """"Month Selection" segmenter - next to "Benchmark Period". Lets you
    benchmark against the BEST months in the window instead of the
    average of all of them."""
    kind_label = column.selectbox(
        "Month Selection", ["All", "Top N Months", "Top % Months"], key=f"{key_prefix}_kind",
        help=(
            '"All" uses the whole benchmark window (default). "Top N/Top %" restricts the mean/median '
            "to only the HIGHEST-value months in that window - a benchmark against the best months, "
            "instead of the average of everything."
        ),
    )
    if kind_label == "Top N Months":
        value = st.number_input(
            "How many months (highest to lowest)", min_value=1, max_value=999, value=12, step=1,
            key=f"{key_prefix}_value_n",
        )
        return transform.MonthSelection("top_n", value)
    if kind_label == "Top % Months":
        value = st.number_input(
            "Which % of months (highest to lowest)", min_value=1, max_value=100, value=25, step=1,
            key=f"{key_prefix}_value_pct",
        )
        return transform.MonthSelection("top_pct", value)
    return transform.MonthSelection("all")


def _select_months_in_current_period(column, key: str) -> int:
    return column.number_input(
        "Months in Current Period", min_value=1, max_value=36, value=1, step=1, key=key,
        help=(
            'How many months to sum into "now": the chosen month plus the N-1 months right before it. '
            '"Current Value" becomes the MEAN (or median, per "Summary Measure" below) of those N '
            "months - not their total - so it can come out LOWER than looking at a single month, if the "
            "months before the chosen one were weaker than it."
        ),
    )


def _current_period_label(measure: str, months_in_current_period: int) -> str:
    return "Current Value" if months_in_current_period <= 1 else f"Current Value ({measure})"


def _current_period_explanation(measure: str, months_in_current_period: int) -> str | None:
    if months_in_current_period <= 1:
        return None
    return (
        f'**Months in Current Period = {months_in_current_period}:** "Current Value" is now the '
        f"**{measure.lower()}** (not the sum) of those {months_in_current_period} months - the chosen "
        f"month plus the {months_in_current_period - 1} months right before it. If the months before "
        "the chosen one were weaker, the value drops versus looking at 1 month alone (and rises if they "
        "were stronger) - that is expected, not an error. The **Benchmark** also now ends before that "
        "whole period, not just before the chosen month, so the same months are never counted twice."
    )


def _value_config(metric: str) -> dict:
    return _CURRENCY_COLUMN if metric == "revenue" else _UNITS_COLUMN


