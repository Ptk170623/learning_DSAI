def _display_ranking(table: pd.DataFrame, metric: str, value_label: str, percent_label: str, include_sale_type: bool = True) -> None:
    if table.empty:
        st.info("No combination reached the selected cutoff in this scope.")
        return
    columns = {"Block": table["block"]}
    if include_sale_type:
        columns["Sale Type"] = table["sale_type"]
    columns["Current Value"] = table["current_value"]
    columns["Benchmark"] = table["benchmark"]
    columns["Classification"] = table["classification"]
    columns[value_label] = table["magnitude"]
    columns[percent_label] = table["percentage"]
    exibir = pd.DataFrame(columns)
    value_col = _value_config(metric)
    st.dataframe(
        exibir, use_container_width=True, hide_index=True,
        column_config={
            "Current Value": value_col, "Benchmark": value_col,
            value_label: value_col, percent_label: _PERCENT_COLUMN,
        },
    )


def page_rises_drops() -> None:
    st.header("Rises and Drops")
    st.caption(
        "Biggest rises and drops by block (and by block x sale type), on the chosen metric, comparing "
        "all blocks at once."
    )

    data = _cached_data_660()
    months = transform.months_available(data)
    if not months:
        st.info("Not enough own-brand sales data for this analysis.")
        return

    c1, c2, c3, c4 = st.columns(4)
    month = c1.selectbox("Month", months, index=len(months) - 1, format_func=lambda m: m.strftime("%m/%Y"), key="month_rd")
    months_in_current_period = _select_months_in_current_period(c2, "months_current_rd")
    client_effort = c3.radio("Client Effort", ["Yes", "All"], horizontal=True, key="effort_rd")
    payment_type = c4.selectbox("Payment Type", PAYMENT_TYPES, index=2, key="payment_rd")

    c5, c6 = st.columns(2)
    metric = c5.selectbox(
        "Metric", list(transform.NAME_METRIC.keys()), format_func=lambda m: transform.NAME_METRIC[m], key="metric_rd",
    )
    cutoff_label = c6.selectbox("Show from", list(CUTOFFS_PCT.keys()), index=1, key="cutoff_rd")
    cutoff_pct = CUTOFFS_PCT[cutoff_label]

    c7, c8, c9 = st.columns(3)
    window = c7.selectbox("Benchmark Period", list(transform.BENCHMARK_WINDOWS.keys()), key="window_rd")
    measure = c8.radio("Summary Measure", ["Mean", "Median"], horizontal=True, key="measure_rd")
    selection = _select_month_selection(c9, "selection_rd")

    explanation = _current_period_explanation(measure, months_in_current_period)
    if explanation is not None:
        st.info(explanation)

    base_block = transform.calculate_base_table_by_block(
        data, client_effort, payment_type, month, window, measure, metric, selection, months_in_current_period,
    )
    base_tv = transform.calculate_base_table(
        data, client_effort, payment_type, month, window, measure, metric, selection, months_in_current_period,
    )

    st.subheader("Biggest Drops")
    st.markdown("**Without sale type**")
    _display_ranking(transform.drops(base_block, cutoff_pct), metric, "Drop", "% of Total Drop", include_sale_type=False)
    st.markdown("**By sale type**")
    _display_ranking(transform.drops(base_tv, cutoff_pct), metric, "Drop", "% of Total Drop")

    st.subheader("Biggest Rises")
    st.markdown("**Without sale type**")
    _display_ranking(transform.rises(base_block, cutoff_pct), metric, "Rise", "% of Total Rise", include_sale_type=False)
    st.markdown("**By sale type**")
    _display_ranking(transform.rises(base_tv, cutoff_pct), metric, "Rise", "% of Total Rise")


